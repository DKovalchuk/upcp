class LLMGateway:
    """Gateway for LLM operations with provider selection."""

    def __init__(self) -> None:
        self._settings = get_settings()
        self._provider = self._create_provider()

    def _create_provider(self) -> LLMProvider:
        """Create the appropriate LLM provider based on configuration."""
        if not self._settings.llm_enabled:
            # Return a no-op provider that raises NotImplementedError
            return _DisabledProvider()

        provider_name = self._settings.llm_provider.lower()
        api_key = self._settings.llm_api_key
        model = self._settings.llm_model

        if provider_name == "openai":
            if not api_key:
                raise ValueError("OPENAI_API_KEY required for OpenAI provider")
            return OpenAIProvider(api_key=api_key, model=model or "gpt-3.5-turbo")
        elif provider_name == "deepseek":
            if not api_key:
                raise ValueError("DEEPSEEK_API_KEY required for DeepSeek provider")
            return DeepSeekProvider(api_key=api_key, model=model or "deepseek-chat")
        elif provider_name == "local":
            return LocalProvider()
        else:
            raise ValueError(f"Unknown LLM provider: {provider_name}")

    def generate_summary(self, text: str) -> str:
        """Generate a summary using the configured provider."""
        return self._provider.generate_summary(text)

    @property
    def is_enabled(self) -> bool:
        """Check if LLM is enabled."""
        return self._settings.llm_enabled


class _DisabledProvider(LLMProvider):
    """Provider that raises error when LLM is disabled."""

    def generate_summary(self, text: str) -> str:
        raise NotImplementedError("LLM is disabled in configuration")