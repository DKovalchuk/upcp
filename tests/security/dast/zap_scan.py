"""ZAP DAST scan wrapper — TASK-0142 / SPEC-0024 Phase 4.

Usage:
    python -m tests.security.dast.zap_scan --out results/zap_<ts>.json
        [--mode baseline|full] [--report-dir tests/security/reports]

Runs zap-baseline.py / zap-full-scan.py (ghcr.io/zaproxy/zaproxy:stable) in
the `zap` compose service against http://app:8080, converts the ZAP JSON
report to the shared upcp-security-result/v1 schema (tests/security/common.py)
and redacts captured tokens in every generated artifact.

Exit codes: 0 = no High/Medium alerts (Low/Info tolerated), 1 = findings,
2 = infra failure (scan produced no JSON report).

Verified against the stable image: the automation scripts have NO ``-H``
flag (getopt ``t:c:u:g:m:n:r:J:w:x:l:hdaijp:sz:P:D:T:IU:``), so the scan runs
unauthenticated on the public surface; file options require ``/zap/wrk`` (the
wrapper bind-mounts the report dir there) and ``docker compose run`` hangs on
an open stdin after container exit (stdin=DEVNULL). Script exit codes:
0=pass, 1=fail alerts, 2=warn alerts, 3=usage error — the JSON report, not
the exit code, decides infra success.
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import yaml

from tests.security.common import check, summarize

REPO_ROOT = Path(__file__).resolve().parents[3]
CONFIG_PATH = Path(__file__).with_name("zap_config.yaml")
COMPOSE_FILE = REPO_ROOT / "docker-compose.test.yml"
RC_MEANING = {0: "pass", 1: "fail alerts", 2: "warn alerts", 3: "usage error"}
# ZAP riskcode -> (check ok, finding severity); tolerance: Low/Info pass.
RISK_MAP = {
    "3": (False, "high"),
    "2": (False, "medium"),
    "1": (True, "low"),
    "0": (True, "info"),
}


def load_config() -> dict[str, Any]:
    with CONFIG_PATH.open(encoding="utf-8") as fh:
        cfg = yaml.safe_load(fh) or {}
    for section in ("scan", "daemon", "redact"):
        cfg.setdefault(section, {})
    cfg.setdefault("rules", {})
    # Authenticated baseline (TASK-0157): defaults keep the section usable
    # even if the mounted config lacks it — credential VALUES are never here,
    # only the env NAMES the in-container hook reads at runtime.
    auth = cfg.setdefault("auth", {})
    auth.setdefault("enabled", True)
    auth.setdefault("login_path", "/auth/login")
    auth.setdefault("env_user", "PERF_EMAIL")
    auth.setdefault("env_password", "PERF_PASSWORD")
    auth.setdefault("probe_urls", ["/", "/api/v1/projects"])
    return cfg


def redact(text: str, patterns: list[str], replacement: str) -> str:
    for pat in patterns:
        text = re.sub(pat, replacement, text)
    return text


def redact_file(path: Path, patterns: list[str], replacement: str) -> None:
    if path.is_file():
        raw = path.read_text(encoding="utf-8", errors="replace")
        cleaned = redact(raw, patterns, replacement)
        if cleaned != raw:
            path.write_text(cleaned, encoding="utf-8")


def write_rules_file(rules: dict[str, Any], report_dir: Path, ts: str) -> str | None:
    """Translate config `rules` into ZAP's native -c format (tab-separated)."""
    if not rules:
        return None
    valid = {"IGNORE", "INFO", "WARN", "FAIL"}
    lines = ["# generated by zap_scan.py from zap_config.yaml rules section"]
    for plugin_id, spec in rules.items():
        if isinstance(spec, dict):
            level = str(spec.get("level", "WARN")).upper()
            note = str(spec.get("note", ""))
        else:
            level, note = str(spec).upper(), ""
        if level not in valid:
            raise SystemExit(f"zap_scan: invalid rule level {level!r} for plugin {plugin_id}")
        lines.append(f"{plugin_id}\t{level}\t{note}")
    name = f"zap_rules_{ts}.conf"
    (report_dir / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return name


def render_auth_hook(cfg: dict[str, Any]) -> str:
    """Generate the authenticated-baseline hook (TASK-0157).

    Mechanism — every step verified against ghcr.io/zaproxy/zaproxy:stable
    (probe evidence recorded in tasks/TASK-0157):

    * the stable automation scripts expose no ``-H`` flag, so auth is
      delivered via ``--hook``: the hook mints a JWT through ``login_path``
      using CONTAINER ENV credentials (only env names are interpolated —
      never values);
    * the global Authorization header is attached with a ZAP REPLACER rule,
      match type ``REQ_HEADER`` — official semantics "will add if not
      present" (replacer add-on help). ``network.addHttpRequestHeader``
      does NOT exist: absent from python-zap v0.6.0 AND from the
      ZAP 2.17.0 API (zipfile scan of zap-2.17.0.jar + network add-on);
    * the ZAP API is called only through the client transport (the
      script-built proxy address lives in ``_ZAPv2__proxies``; the script's
      own ``wait_for_zap_start`` uses the same path before this hook runs);
    * ``probe_urls`` are fetched THROUGH the ZAP proxy — the passive scan
      records the responses and the HTTP status proves the injected header
      was accepted (401/403 = not authenticated = strict failure);
    * the hook writes an ``ok|error`` status file the wrapper validates —
      no silent unauthenticated fallback (wrapper exits 2).
    """
    auth = cfg["auth"]
    probes = ",\n    ".join(repr(u) for u in auth["probe_urls"])
    return f'''# Generated by tests/security/dast/zap_scan.py — TASK-0157 authenticated
# baseline hook. No secrets: credentials come from the container env
# ({auth["env_user"]}/{auth["env_password"]}); only names/paths are embedded.
#
# Why replacer REQ_HEADER (evidence in tasks/TASK-0157): python-zap v0.6.0
# has no network.addHttpRequestHeader AND ZAP 2.17.0 exposes no such API
# action; replacer match type REQ_HEADER is documented to ADD the header
# when it is absent, so one rule covers spider / active-scan / probe traffic.
import json
import os
import urllib.error
import urllib.request

LOGIN_PATH = {auth["login_path"]!r}
ENV_USER = {auth["env_user"]!r}
ENV_PASSWORD = {auth["env_password"]!r}
PROBE_URLS = [
    {probes},
]
STATUS_FILE = "/zap/wrk/zap_auth_hook_status.txt"
RULE_DESCRIPTION = "UPCP authenticated baseline Authorization (TASK-0157)"


def _probe(opener, url):
    """Fetch url THROUGH the ZAP proxy -> (http_status | None, error_detail).

    The proxy path is what the scan itself uses: the passive scan records
    the response, and the status code proves the injected Authorization
    header was accepted (HTTPError is evidence, not a crash).
    """
    resp = None
    try:
        resp = opener.open(urllib.request.Request(url), timeout=30)
        return resp.getcode(), ""
    except urllib.error.HTTPError as exc:
        return exc.code, ""
    except Exception as exc:
        return None, type(exc).__name__ + ": " + str(exc)[:160]
    finally:
        if resp is not None:
            resp.close()


def zap_started(zap, target):
    base = target.rstrip("/")
    status = "error unknown"
    try:
        email = os.environ[ENV_USER]
        password = os.environ[ENV_PASSWORD]
        req = urllib.request.Request(
            base + LOGIN_PATH,
            data=json.dumps({{"email": email, "password": password}}).encode("utf-8"),
            headers={{"Content-Type": "application/json"}},
            method="POST",
        )
        with urllib.request.urlopen(req, timeout=20) as resp:
            token = json.loads(resp.read())["access_token"]
        print("auth_hook: minted token (REDACTED)")
        res = zap.replacer.add_rule(
            description=RULE_DESCRIPTION,
            enabled="true",
            matchtype="REQ_HEADER",
            matchregex="false",
            matchstring="Authorization",
            replacement="Bearer " + token,
        )
        print("auth_hook: replacer addRule -> " + repr(res)[:200])
        if str(res).strip().lower() != "ok":
            status = "error header: addRule returned " + repr(res)[:200]
        else:
            proxy_cfg = getattr(zap, "_ZAPv2__proxies", None) or {{}}
            proxy = proxy_cfg.get("http")
            if not proxy:
                raise RuntimeError("client proxy address missing (_ZAPv2__proxies)")
            print("auth_hook: probe via proxy " + proxy)
            opener = urllib.request.build_opener(
                urllib.request.ProxyHandler({{"http": proxy}})
            )
            failures = []
            codes = []
            for path in PROBE_URLS:
                code, err = _probe(opener, base + path)
                print(
                    "auth_hook: probe " + path + " -> "
                    + ("HTTP " + str(code) if code is not None else err)
                )
                if code is None or code in (401, 403) or code >= 500:
                    failures.append(path + ": " + (err or "HTTP " + str(code)))
                codes.append("err" if code is None else str(code))
            if failures:
                status = "error probe " + "; ".join(failures)
            else:
                status = (
                    "ok header=replacer probes=" + str(len(PROBE_URLS))
                    + " codes=" + ",".join(codes)
                )
    except Exception as exc:
        status = "error " + type(exc).__name__ + ": " + str(exc)[:200]
        print("auth_hook failed: " + status)
    with open(STATUS_FILE, "w", encoding="utf-8") as fh:
        fh.write(status + "\\n")
'''


def build_command(
    mode: str,
    target: str,
    spider_minutes: int,
    html_name: str,
    json_name: str,
    rules_name: str | None,
    daemon: dict[str, Any],
    report_dir: Path,
    hook_name: str | None = None,
) -> list[str]:
    script = "zap-baseline.py" if mode == "baseline" else "zap-full-scan.py"
    inner = [script, "-t", target, "-m", str(spider_minutes), "-r", html_name, "-J", json_name]
    if rules_name:
        inner += ["-c", rules_name]
    if hook_name:
        # zap-baseline.py option — must live inside the `sh -c` script
        inner += ["--hook", f"/zap/wrk/{hook_name}"]
    if daemon:
        pairs = " ".join(
            f"-config {k}={str(v).lower() if isinstance(v, bool) else v}" for k, v in daemon.items()
        )
        inner += ["-z", pairs]
    return [
        "docker",
        "compose",
        "-f",
        str(COMPOSE_FILE),
        "--profile",
        "security",
        "run",
        "--rm",
        "-T",
        "--no-deps",
        "-v",
        f"{report_dir.resolve()}:/zap/wrk",
        "zap",
        "sh",
        "-c",
        shlex.join(inner),
    ]


def parse_alerts(
    zap_json: Path, patterns: list[str], replacement: str
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """One check per ZAP alert; High/Medium fail, Low/Info pass (tolerance)."""
    data = json.loads(redact(zap_json.read_text(encoding="utf-8"), patterns, replacement))
    checks: list[dict[str, Any]] = []
    counts = {"high": 0, "medium": 0, "low": 0, "info": 0}
    for site in data.get("site", []):
        site_name = site.get("@name", "")
        for alert in site.get("alerts", []):
            ok, severity = RISK_MAP.get(str(alert.get("riskcode", "1")), (True, "low"))
            risk_desc = alert.get("riskdesc", "?")
            counts[severity] += 1
            inst = (alert.get("instances") or [{}])[0]
            detail = "; ".join(
                filter(
                    None,
                    [
                        f"site={site_name}" if site_name else "",
                        f"uri={inst.get('uri', '')}" if inst.get("uri") else "",
                        f"param={inst.get('param')}" if inst.get("param") else "",
                        f"evidence={inst.get('evidence')}" if inst.get("evidence") else "",
                        f"count={alert.get('count', 1)}",
                    ],
                )
            )
            checks.append(
                check(
                    f"ZAP [{risk_desc}] {alert.get('alert', 'unnamed')} "
                    f"(plugin {alert.get('pluginid', '?')})",
                    "dast",
                    ok,
                    expected="no High/Medium ZAP alerts" if not ok else "informational only",
                    actual=risk_desc,
                    detail=detail,
                    severity=severity if not ok else "",
                )
            )
    return checks, counts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="zap_scan", description="ZAP DAST scan via docker compose"
    )
    parser.add_argument("--out", required=True, help="result JSON path (upcp-security-result/v1)")
    parser.add_argument("--mode", choices=("baseline", "full"), default="baseline")
    parser.add_argument("--report-dir", default=str(REPO_ROOT / "tests" / "security" / "reports"))
    args = parser.parse_args(argv)

    cfg = load_config()
    target = str(cfg["scan"].get("target", "http://app:8080"))
    report_dir = Path(args.report_dir)
    if not report_dir.is_absolute():
        report_dir = (Path.cwd() / report_dir).resolve()
    report_dir.mkdir(parents=True, exist_ok=True)

    ts = time.strftime("%Y%m%d-%H%M%S")
    prefix = str(cfg["scan"].get("report_prefix", "zap"))
    html_name, json_name = f"{prefix}_{args.mode}_{ts}.html", f"{prefix}_{args.mode}_{ts}.json"
    spider_key = "full_spider_minutes" if args.mode == "full" else "spider_minutes"
    spider = int(cfg["scan"].get(spider_key, 3 if args.mode == "full" else 1))
    try:
        rules_name = write_rules_file(cfg["rules"], report_dir, ts)
    except OSError as exc:
        print(f"zap_scan: cannot write rules file: {exc}", file=sys.stderr)
        return 2

    auth = cfg["auth"]
    hook_name = f"zap_auth_hook_{ts}.py" if auth.get("enabled") else None
    hook_path = report_dir / hook_name if hook_name else None
    status_path = report_dir / "zap_auth_hook_status.txt"
    if hook_path is not None:
        status_path.unlink(missing_ok=True)
        try:
            hook_path.write_text(render_auth_hook(cfg), encoding="utf-8")
        except OSError as exc:
            print(f"zap_scan: cannot write auth hook: {exc}", file=sys.stderr)
            return 2

    def _cleanup_hook() -> None:
        for path in (hook_path, status_path):
            if path is not None:
                path.unlink(missing_ok=True)

    cmd = build_command(
        args.mode,
        target,
        spider,
        html_name,
        json_name,
        rules_name,
        cfg["daemon"],
        report_dir,
        hook_name=hook_name,
    )
    timeout = 600 if args.mode == "baseline" else 900
    print(f"zap_scan: mode={args.mode} target={target} timeout={timeout}s")
    start = time.time()
    try:
        proc = subprocess.run(
            cmd,
            cwd=REPO_ROOT,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        print("zap_scan: scan timed out (infra failure)", file=sys.stderr)
        _cleanup_hook()
        return 2
    duration = int(time.time() - start)

    redact_cfg = cfg["redact"]
    patterns = list(redact_cfg.get("patterns", []))
    replacement = str(redact_cfg.get("replacement", "REDACTED"))
    # Persist (redacted) scan console output as evidence, always.
    log_path = report_dir / f"{prefix}_{args.mode}_{ts}.log"
    log_text = redact((proc.stdout or "") + (proc.stderr or ""), patterns, replacement)
    if log_text.strip():
        log_path.write_text(log_text, encoding="utf-8")

    json_report, html_report = report_dir / json_name, report_dir / html_name
    # The JSON report is the source of truth: ZAP scripts exit 1/2 on
    # findings; rc=3 (usage error) never produces a report.
    if not json_report.is_file():
        tail = "\n".join(log_text.splitlines()[-15:])
        print(f"zap_scan: scan failed rc={proc.returncode}\n{tail}", file=sys.stderr)
        _cleanup_hook()
        return 2
    if hook_path is not None:
        # Strict authenticated-baseline contract (TASK-0157): the hook must
        # report a minted token + successful probes. A silent unauthenticated
        # fallback would defeat the point — broken login fails the suite.
        status = (
            status_path.read_text(encoding="utf-8", errors="replace").strip()
            if status_path.is_file()
            else ""
        )
        if not status.startswith("ok"):
            print(
                f"zap_scan: authenticated hook failed ({status or 'no status file'})",
                file=sys.stderr,
            )
            _cleanup_hook()
            return 2
    redact_file(json_report, patterns, replacement)
    redact_file(html_report, patterns, replacement)
    try:
        checks, counts = parse_alerts(json_report, patterns, replacement)
    except (json.JSONDecodeError, OSError) as exc:
        print(f"zap_scan: cannot parse ZAP report: {exc}", file=sys.stderr)
        _cleanup_hook()
        return 2

    checks.insert(
        0,
        check(
            "ZAP scan executed",
            "dast",
            True,
            expected="scripted scan completes and emits JSON report",
            actual=f"rc={proc.returncode} ({RC_MEANING.get(proc.returncode, '?')}), "
            f"duration={duration}s",
            detail=f"script={'zap-baseline.py' if args.mode == 'baseline' else 'zap-full-scan.py'}; "
            f"reports={html_name},{json_name}; log={log_path.name}; "
            + (
                f"authenticated hook scan (no -H on stable scripts; minted JWT, "
                f"probed {len(auth.get('probe_urls', []))} urls)"
                if hook_name
                else "unauthenticated public-surface scan (stable zap scripts have no -H flag)"
            ),
        ),
    )
    result = summarize(
        "zap",
        target,
        checks,
        mode=args.mode,
        report_html=str(html_report),
        report_json=str(json_report),
        scan_log=str(log_path),
        duration_seconds=duration,
        alert_counts=counts,
    )
    out_path = Path(args.out)
    if not out_path.is_absolute():
        out_path = Path.cwd() / out_path
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    redact_file(out_path, patterns, replacement)

    failed = [c for c in checks if c["status"] == "fail"]
    print(
        f"zap_scan: {len(checks)} checks, {len(failed)} findings "
        f"(high={counts['high']} medium={counts['medium']} low={counts['low']} "
        f"info={counts['info']}) -> {out_path}"
    )
    _cleanup_hook()
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
