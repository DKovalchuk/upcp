#!/usr/bin/env python3
"""Format Kali agent raw outputs into the shared security-result schema.

Runs inside the kali container (python3, no project deps) as the final step
of run.sh. Parses the raw tool outputs (nmap/nikto/sqlmap from checks.py,
plus the curl security-header audit defined here) and writes:
  - result JSON (--out): schema "upcp-security-result/v1", suite "kali",
    structurally identical to tests/security/common.py:summarize() output
    (common.py is host-only and not mounted, hence the local helpers);
  - markdown report (--md) with findings and the full check table.

JWT/bearer tokens are redacted from both outputs before writing.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from checks import check, parse_nikto, parse_nmap, parse_sqlmap, tail

REDACT = [
    (re.compile(r"eyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]*"), "REDACTED"),
    (re.compile(r"(?i)bearer\s+[A-Za-z0-9._~+/=-]{15,}"), "Bearer REDACTED"),
]


def redact(text: str) -> str:
    for pat, repl in REDACT:
        text = pat.sub(repl, text)
    return text


def parse_headers(raw: Path, headers_rc: int, target: str) -> list[dict]:
    text = tail(raw / "headers.txt", limit=10_000)
    if headers_rc != 0 or not text:
        return [
            check(
                "headers: /health reachable",
                "headers",
                False,
                expected="HTTP 200 from /health",
                actual=f"curl rc={headers_rc}",
                detail="target unreachable",
                severity="high",
            )
        ]
    status = re.search(r"HTTP/[\d.]+ (\d+)", text)
    code = int(status.group(1)) if status else 0
    checks = [
        check(
            "headers: /health reachable",
            "headers",
            code == 200,
            expected="HTTP 200",
            actual=f"HTTP {code}",
            detail=f"GET {target}/health",
        )
    ]
    fields = {
        m.group(1).lower(): m.group(2).strip()
        for m in re.finditer(r"^([A-Za-z0-9-]+):\s*(.+)$", text, re.M)
    }
    wanted = {
        "content-security-policy": "CSP missing — XSS mitigation header absent",
        "x-frame-options": "X-Frame-Options missing — clickjacking protection absent",
        "x-content-type-options": "X-Content-Type-Options missing — MIME sniffing possible",
        "strict-transport-security": "HSTS absent (note: effective only behind TLS)",
    }
    for header, msg in wanted.items():
        present = header in fields
        checks.append(
            check(
                f"headers: {header}",
                "headers",
                present,
                expected="header present",
                actual=fields.get(header, "absent"),
                detail="present" if present else msg,
                severity="" if present else "low",
            )
        )
    server = fields.get("server", "")
    leak = bool(re.search(r"uvicorn|gunicorn|uwsgi|nginx|apache|werkzeug", server, re.I))
    checks.append(
        check(
            "headers: server banner disclosure",
            "headers",
            not leak,
            expected="no software banner",
            actual=server or "absent",
            detail="Server header discloses software stack"
            if leak
            else "no server banner or unrecognized",
            severity="info" if leak else "",
        )
    )
    return checks


def build_markdown(meta: dict, checks: list[dict]) -> str:
    failed = [c for c in checks if c["status"] == "fail"]
    lines = [
        f"# Kali pentest agent report — {meta['ts']}",
        "",
        f"- **Target:** {meta['target']}",
        f"- **Duration:** {meta['duration']}s",
        f"- **Auth used for sqlmap:** {meta['auth_used']}",
        f"- **Checks:** {len(checks)} total, {len(checks) - len(failed)} passed, "
        f"{len(failed)} failed",
        f"- **Tool budgets:** nikto {meta['nikto_max']}s, sqlmap {meta['sqlmap_max']}s",
        "",
        "## Findings",
        "",
    ]
    if not failed:
        lines.append("_No findings._")
    for c in failed:
        sev = (c.get("severity") or "medium").upper()
        lines.append(f"- **[{sev}] {c['name']}** — {c.get('detail') or c.get('actual', '')}")
    lines += ["", "## Checks", "", "| Status | Check | Actual |", "|---|---|---|"]
    for c in checks:
        lines.append(
            "| {} | {} | {} |".format(
                "PASS" if c["status"] == "pass" else "FAIL",
                c["name"].replace("|", "/"),
                (c.get("actual") or "").replace("|", "/")[:80],
            )
        )
    lines += [
        "",
        "_Generated by tests/security/kali/run.sh — schema "
        "upcp-security-result/v1. Tokens redacted._",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", required=True)
    ap.add_argument("--ts", required=True)
    ap.add_argument("--raw", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--md", required=True)
    for rc_flag in ("nmap", "nikto", "sqlmap", "headers"):
        ap.add_argument(f"--{rc_flag}-rc", type=int, required=True)
    ap.add_argument("--sqlmap-max", type=int, required=True)
    ap.add_argument("--nikto-max", type=int, required=True)
    ap.add_argument("--auth-used", choices=("yes", "no"), required=True)
    ap.add_argument("--duration", type=int, required=True)
    args = ap.parse_args()

    raw = Path(args.raw)
    checks = (
        parse_nmap(raw, args.nmap_rc)
        + parse_nikto(raw, args.nikto_rc, args.nikto_max)
        + parse_sqlmap(raw, args.sqlmap_rc, args.sqlmap_max)
        + parse_headers(raw, args.headers_rc, args.target)
    )
    failed = [c for c in checks if c["status"] == "fail"]
    result = {
        "schema": "upcp-security-result/v1",
        "suite": "kali",
        "target": args.target,
        "checks": checks,
        "findings": [
            {
                "severity": c.get("severity") or "medium",
                "title": c["name"],
                "category": c["category"],
                "detail": c.get("detail") or c.get("actual", ""),
            }
            for c in failed
        ],
        "summary": {
            "total": len(checks),
            "passed": len(checks) - len(failed),
            "failed": len(failed),
        },
        "duration_seconds": args.duration,
        "tool_budgets": {
            "nikto_max_seconds": args.nikto_max,
            "sqlmap_max_seconds": args.sqlmap_max,
        },
        "auth_used_for_sqlmap": args.auth_used,
    }
    meta = {
        "target": args.target,
        "ts": args.ts,
        "duration": args.duration,
        "auth_used": args.auth_used,
        "sqlmap_max": args.sqlmap_max,
        "nikto_max": args.nikto_max,
    }
    Path(args.out).write_text(
        redact(json.dumps(result, indent=2, ensure_ascii=False)) + "\n", encoding="utf-8"
    )
    Path(args.md).write_text(redact(build_markdown(meta, checks)), encoding="utf-8")
    print(f"format_result: {len(checks)} checks, {len(failed)} failed -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
